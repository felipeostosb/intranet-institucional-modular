DROP TABLE IF EXISTS mod03.t_modulo03_registros CASCADE;

-- -----------------------------------------------------------------------------
-- 1. ESPECIALIDAD
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS mod03.especialidad (
    id_especialidad INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL UNIQUE,
    estado VARCHAR(20) NOT NULL DEFAULT 'Activo',
    CONSTRAINT ck_especialidad_estado
        CHECK (estado IN ('Activo', 'Inactivo'))
);

-- -----------------------------------------------------------------------------
-- 2. ALMACEN
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS mod03.almacen (
    id_almacen INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_especialidad INTEGER NULL,
    nombre VARCHAR(100) NOT NULL UNIQUE,
    ubicacion VARCHAR(150),
    responsable VARCHAR(150),
    estado VARCHAR(20) NOT NULL DEFAULT 'Activo',

    CONSTRAINT fk_almacen_especialidad
        FOREIGN KEY (id_especialidad)
        REFERENCES mod03.especialidad(id_especialidad),

    CONSTRAINT ck_almacen_estado
        CHECK (estado IN ('Activo', 'Inactivo'))
);

-- -----------------------------------------------------------------------------
-- 3. AMBIENTE
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS mod03.ambiente (
    id_ambiente INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_especialidad INTEGER NULL,
    nombre VARCHAR(100) NOT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'Activo',

    CONSTRAINT fk_ambiente_especialidad
        FOREIGN KEY (id_especialidad)
        REFERENCES mod03.especialidad(id_especialidad),

    CONSTRAINT ck_ambiente_estado
        CHECK (estado IN ('Activo', 'Inactivo')),

    CONSTRAINT uq_ambiente_especialidad
        UNIQUE (id_especialidad, nombre)
);

-- -----------------------------------------------------------------------------
-- 4. CLASIFICACIONES DE BIEN
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS mod03.clasificaciones_bien (
    id_clasificacion INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(80) NOT NULL UNIQUE,
    estado VARCHAR(20) NOT NULL DEFAULT 'Activo',

    CONSTRAINT ck_clasificacion_estado
        CHECK (estado IN ('Activo', 'Inactivo'))
);

-- -----------------------------------------------------------------------------
-- 5. BIEN
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS mod03.bien (
    id_bien INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_almacen INTEGER NOT NULL,
    id_clasificacion INTEGER NOT NULL,

    cbi VARCHAR(30) NOT NULL UNIQUE,
    codigo_inventario VARCHAR(50) UNIQUE,
    descripcion VARCHAR(150) NOT NULL,
    marca VARCHAR(100),
    modelo VARCHAR(100),
    serie VARCHAR(100) UNIQUE,

    procedencia VARCHAR(30) NOT NULL DEFAULT 'Donación',
    fecha_ingreso DATE NOT NULL DEFAULT CURRENT_DATE,

    estado VARCHAR(30) NOT NULL DEFAULT 'Bueno',
    observacion TEXT,

    CONSTRAINT fk_bien_almacen
        FOREIGN KEY (id_almacen)
        REFERENCES mod03.almacen(id_almacen),

    CONSTRAINT fk_bien_clasificacion
        FOREIGN KEY (id_clasificacion)
        REFERENCES mod03.clasificaciones_bien(id_clasificacion),

    CONSTRAINT ck_bien_procedencia
        CHECK (procedencia IN ('Donación', 'Adquisición', 'Transferencia', 'Otro')),

    CONSTRAINT ck_bien_estado
        CHECK (estado IN (
            'Bueno',
            'Regular',
            'Malo',
            'En reparación',
            'Inoperativo',
            'Baja en trámite',
            'De baja'
        ))
);

-- -----------------------------------------------------------------------------
-- 6. ASIGNACION
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS mod03.asignacion (
    id_asignacion INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_bien INTEGER NOT NULL,
    id_ambiente INTEGER NOT NULL,
    responsable VARCHAR(150),
    fecha_asignacion DATE NOT NULL DEFAULT CURRENT_DATE,
    fecha_fin DATE,
    estado VARCHAR(20) NOT NULL DEFAULT 'Activa',
    observacion TEXT,

    CONSTRAINT fk_asignacion_bien
        FOREIGN KEY (id_bien)
        REFERENCES mod03.bien(id_bien),

    CONSTRAINT fk_asignacion_ambiente
        FOREIGN KEY (id_ambiente)
        REFERENCES mod03.ambiente(id_ambiente),

    CONSTRAINT ck_asignacion_estado
        CHECK (estado IN ('Activa', 'Finalizada')),

    CONSTRAINT ck_asignacion_fechas
        CHECK (fecha_fin IS NULL OR fecha_fin >= fecha_asignacion)
);

-- -----------------------------------------------------------------------------
-- 7. TRANSFERENCIA
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS mod03.transferencia (
    id_transferencia INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_bien INTEGER NOT NULL,
    id_almacen_origen INTEGER NOT NULL,
    id_almacen_destino INTEGER NOT NULL,

    fecha_solicitud TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_salida TIMESTAMP WITH TIME ZONE,
    fecha_recepcion TIMESTAMP WITH TIME ZONE,

    motivo VARCHAR(150) NOT NULL,
    responsable_origen VARCHAR(150),
    responsable_destino VARCHAR(150),

    estado_movimiento VARCHAR(30) NOT NULL DEFAULT 'Pendiente de recepción',
    documento VARCHAR(100),
    observacion TEXT,

    CONSTRAINT fk_transferencia_bien
        FOREIGN KEY (id_bien)
        REFERENCES mod03.bien(id_bien),

    CONSTRAINT fk_transferencia_origen
        FOREIGN KEY (id_almacen_origen)
        REFERENCES mod03.almacen(id_almacen),

    CONSTRAINT fk_transferencia_destino
        FOREIGN KEY (id_almacen_destino)
        REFERENCES mod03.almacen(id_almacen),

    CONSTRAINT ck_transferencia_origen_destino
        CHECK (id_almacen_origen <> id_almacen_destino),

    CONSTRAINT ck_transferencia_estado
        CHECK (estado_movimiento IN (
            'Pendiente',
            'En tránsito',
            'Pendiente de recepción',
            'Recepcionado',
            'Cancelado'
        )),

    CONSTRAINT ck_transferencia_fechas
        CHECK (fecha_salida IS NULL OR fecha_salida >= fecha_solicitud)
);

-- -----------------------------------------------------------------------------
-- 8. INVENTARIO ANUAL
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS mod03.inventario_anual (
    id_inventario INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_bien INTEGER NOT NULL,
    anio INTEGER NOT NULL,
    fecha_verificacion DATE NOT NULL DEFAULT CURRENT_DATE,
    resultado VARCHAR(20) NOT NULL DEFAULT 'Físico',
    observacion TEXT,

    CONSTRAINT fk_inventario_anual_bien
        FOREIGN KEY (id_bien)
        REFERENCES mod03.bien(id_bien),

    CONSTRAINT ck_inventario_anual_anio
        CHECK (anio BETWEEN 2000 AND 2100),

    CONSTRAINT ck_inventario_anual_resultado
        CHECK (resultado IN ('Físico', 'Faltante', 'Sobrante')),

    CONSTRAINT uq_inventario_anual_bien_anio
        UNIQUE (id_bien, anio)
);

