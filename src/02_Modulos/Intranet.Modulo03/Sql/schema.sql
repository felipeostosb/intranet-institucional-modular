-- =============================================================================
-- VISTA PARA CONSULTA DEL INVENTARIO
-- =============================================================================
CREATE OR REPLACE VIEW mod03.v_inventario AS
SELECT
    b.id_bien,
    b.cbi,
    b.codigo_inventario,
    b.descripcion,
    cb.nombre AS clasificacion,
    b.marca,
    b.modelo,
    b.serie,
    b.procedencia,
    b.fecha_ingreso,
    b.estado,
    a.nombre AS almacen_actual,
    a.ubicacion AS ubicacion_almacen,
    amb.nombre AS ambiente_actual,
    asg.responsable,
    b.observacion
FROM mod03.bien b
JOIN mod03.almacen a
    ON a.id_almacen = b.id_almacen
JOIN mod03.clasificaciones_bien cb
    ON cb.id_clasificacion = b.id_clasificacion
LEFT JOIN LATERAL (
    SELECT *
    FROM mod03.asignacion ax
    WHERE ax.id_bien = b.id_bien
      AND ax.estado = 'Activa'
    ORDER BY ax.fecha_asignacion DESC, ax.id_asignacion DESC
    LIMIT 1
) AS asg ON TRUE
LEFT JOIN mod03.ambiente amb
    ON amb.id_ambiente = asg.id_ambiente;

-- =============================================================================
-- VISTA PARA TRANSFERENCIAS
-- =============================================================================
CREATE OR REPLACE VIEW mod03.v_transferencias AS
SELECT
    t.id_transferencia,
    b.cbi,
    b.descripcion,
    ao.nombre AS almacen_origen,
    ad.nombre AS almacen_destino,
    t.fecha_solicitud,
    t.fecha_salida,
    t.fecha_recepcion,
    t.estado_movimiento,
    t.motivo,
    t.responsable_origen,
    t.responsable_destino,
    t.documento,
    t.observacion
FROM mod03.transferencia t
JOIN mod03.bien b
    ON b.id_bien = t.id_bien
JOIN mod03.almacen ao
    ON ao.id_almacen = t.id_almacen_origen
JOIN mod03.almacen ad
    ON ad.id_almacen = t.id_almacen_destino;

-- =============================================================================
-- VISTA PARA INVENTARIO ANUAL
-- =============================================================================
CREATE OR REPLACE VIEW mod03.v_inventario_anual AS
SELECT
    ia.id_inventario,
    ia.anio,
    ia.fecha_verificacion,
    ia.resultado,
    b.cbi,
    b.descripcion,
    b.serie,
    a.nombre AS almacen_actual,
    ia.observacion
FROM mod03.inventario_anual ia
JOIN mod03.bien b
    ON b.id_bien = ia.id_bien
JOIN mod03.almacen a
    ON a.id_almacen = b.id_almacen;



